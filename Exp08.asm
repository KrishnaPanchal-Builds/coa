ORG 100H
LEA SI, ARR
MOV CX, N-1
OUTER_LOOP:
 PUSH CX
 LEA SI, ARR
 MOV CX, N-1
INNER_LOOP:
 MOV AL, [SI]
 MOV AH, [SI+1]
 CMP AL, AH
 JBE NO_SWAP
 MOV [SI], AH
 MOV [SI+1], AL
NO_SWAP:
 INC SI
 LOOP INNER_LOOP
 POP CX
 LOOP OUTER_LOOP
; ---------- PRINT SORTED ARRAY ----------
LEA SI, ARR
MOV CX, N
PRINT_LOOP:
 MOV DL, [SI]
 ADD DL, '0' ; convert digit to ASCII
 MOV AH, 02H
 INT 21H
 MOV DL, ' '
 MOV AH, 02H
 INT 21H
 INC SI
 LOOP PRINT_LOOP
 MOV AH, 4CH

 INT 21H
ARR DB 5, 2, 9, 1, 7, 6, 3, 8
N EQU 8
END
ret
